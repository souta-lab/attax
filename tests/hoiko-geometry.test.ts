function normalized(cells: readonly { readonly x: number; readonly y: number }[]): string[] {
  return cells.map((cell) => `${cell.x},${cell.y}`).sort();
}

describe("native Hoiko piece geometry", () => {
  for (const kind of Object.keys(NATIVE_SHAPES) as PieceKind[]) {
    const rotations = NATIVE_SHAPES[kind];
    for (let rotation = 0; rotation < rotations.length; rotation += 1) {
      test(`${kind} rotation ${rotation} uses native anchor coordinates`, () => {
        const expected = rotations[rotation];
        expect(expected).toBeDefined();
        expect(normalized(cellsFor(kind, rotation))).toEqual(
          normalized((expected ?? []).map(([x, y]) => ({ x, y }))),
        );
      });
    }
  }
});
