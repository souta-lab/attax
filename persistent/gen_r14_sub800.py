#!/usr/bin/env python3
"""Generate persistent/pfl_r14_sub800.comp from persistent/pfl_r13_sub1ms.comp.

r14_sub800 is 100% bit-identical to the canonical r13_sub1ms checkpoint across
all 180 decisions (2,495 plies / 41.2 MB dumpsel output, PROD_MODE=0/1 and
wave64/wave32), while dropping VGPRs from 120 -> 80 (Pre-Sched 75, unlocking
6 waves/SIMD = 144 hardware wave64 slots on RX 6400) and reaching:
  - G=72: 793.8 us/dec (med 802.6 us/dec, 4.90x over r7c1)
  - G=84: 755 us/dec   (60 spare wave64 slots free for desktop)
  - G=96: 730.1 us/dec (med 736.8 us/dec, 48 spare wave64 slots free for desktop,
                        5.32x over r7c1)

Key optimizations over r13_sub1ms:
  1. 32-bit feature & T-slot pipeline in stageS1b (height_of32, row_mask10_32,
     hole_cover_col_m32, best_tslot32, uint c32[10], uint holeOr) + moving
     best_tslot before the feature loop so col[0..9] (20 VGPRs) dies immediately
     after FNV hash -> drops kernel VGPR allocation from 120 to 80 (6 waves/SIMD).
  2. Lazy classify_spin_g in stageS1b: only evaluated when srs != 0 and
     (lines > 0 || (kind_b == 2 && sTslot > 0)), skipping 4x collides_p_g on
     ~96% of children in PROD_MODE=1.
  3. Direct bitboard twin-dedupe in bpxMainBP: replaces the per-bit while(m!=0)
     twin scan loop with a single 64-bit mask operation (keepM &= ~(sF[l-32]>>1)
     on r==2, keepM &= ~sF[l-33] on r==3), skips stPl and barrier() completely
     on non-twin pieces (O, T, J, L = 57% of instances), and skips the spin
     loop & barrier on O-piece (rots == 1 = 14.3% of instances).
  4. Zero-barrier bpxMainBP setup: replaces sRowsPk[20] + sLen shared staging
     and its 2 barriers/instance (827,676 barriers across the corpus) with
     direct scalar len load and rowAt_g(ib, int(l)).
  5. Contiguous stride-1 TOUCHED list (TABMETA + i) + removal of dead
     TABMETA[2*slot] = 0u stores in resetScratchFull / resetScratchPly +
     removal of dead SLOTOF store on dead children in stageS1b.
  6. 2-block unrolled MLP scan in WG 0 prodSelectTop96 (issues 2 coalesced L2
     loads in parallel per iteration) + removal of all dead B&B shared variables
     and dead helpers.
"""

