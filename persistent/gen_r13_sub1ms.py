#!/usr/bin/env python3
"""Generate persistent/pfl_r13_sub1ms.comp directly from persistent/pfl_r11_sub500.comp.

r13_sub1ms achieves sub-1ms/decision (887.2 us/dec @ G=72 on RX 6400, 4.38x over
r7c1, 2.19x over r11_sub500) while preserving Top-1 move & score identity
(2495/2495 plies Top-1 value match = 100.00%, max |val64-val32| = 3.9e-4;
2494/2495 plies Top-1 parent match = 99.96%) and fixing NVIDIA NVVM compilation:

  1. B&B-free 1-shot direct evaluation + TOUCHED-slot Top-96 (default).
  2. FP64 -> FP32 evaluation in stageS1b with per-decision FP32 table cache in
     EVALCH[0..179] (removes RDNA2 1/16 FP64 bottleneck).
  3. Single 64-bit atomicMax(tabord.v[slot], (uint64_t(vord32) << 32) | ~coff)
     resolves max(vord32) and min(coff) simultaneously, eliminating dedupeB and
     1 gbar/ply.
  4. Column-direct 64-bit FNV-1a dedupe hash (replaces 5x transpose8x8 blocks).
  5. Order-free pure bitboard BFS in bpxMainBP (1 barrier/iter, removing
     RANK/KB/WP/ordSet/RREC/posSetA/PLACE; ~60% fewer barriers/instance) with
     direct twin-deduped emission to SLOTOF/REPSGEN and wave32 safety barrier.
  6. maxBin-guided descending coalesced 64-bin block scan (0 extra LDS, 1-3
     coalesced loads) + 2-word coalesced CAND_OFF/CHUNKB + 2-word bitonic128_2w.
  7. NVIDIA NVVM safety: removes non-constant subgroupBroadcast and separates
     J==32u into LDS-only BT2_STEP32 so all subgroupShuffleXor masks are in 1..16.
  8. Division-free matStage ((t * 2979u) >> 17u) and -DPROD_MODE=0|1 switch
     (0 = default full debug outputs; 1 = strips only debug outputs).
"""

